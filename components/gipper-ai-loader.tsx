export function GipperAiLoader() {
  const ref = useRef<HTMLDivElement>(null)

  /*
   * Safari does not honour the pathLength attribute, so a dash pattern
   * normalised against it comes out shorter than the path. A dash shorter
   * than the line it runs along simply repeats — which is why every glyph
   * appeared to be drawn twice. Measuring the real length fixes it everywhere.
   */
  useLayoutEffect(() => {
    ref.current?.querySelectorAll('path').forEach((path) => {
      path.style.setProperty('--len', String(path.getTotalLength()))
    })
  }, [])

  return (
    <div className="ai-loader not-prose" ref={ref} role="img" aria-label="Loading indicator">
      {PATHS.map((p) => (
        <svg key={p.d} viewBox={p.viewBox} preserveAspectRatio="xMidYMid meet" aria-hidden="true">
          <path d={p.d} />
        </svg>
      ))}
    </div>
  )
}
